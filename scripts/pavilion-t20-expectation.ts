/**
 * Project Pavilion B7: the T20 runs-still-to-come table, measured from the game's own model.
 *
 * Runs the frozen 100-match Pass 07B corpus (fixture autopilot, synthetic-alpha-01) in memory, reads each first
 * innings ball by ball, and records, at the start of every over, the runs the innings went on to add. First innings
 * only: a chase stops when the target is reached, so its remaining runs are not the side's scoring power.
 *
 *   node --import tsx scripts/pavilion-t20-expectation.ts           writes packages/projections/src/t20-expectation-table.ts
 *   node --import tsx scripts/pavilion-t20-expectation.ts --check   fails if the committed table differs
 *
 * It reads the model; it does not change it. The table describes this synthetic model, not real cricket.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { validateT20MatchSetup, createT20CorpusRequest, runFixtureT20, projectT20Scorecard } from "@lcxxvi/simulation";

const OUT = "packages/projections/src/t20-expectation-table.ts";
const corpusPath = "tests/fixtures/t20/seed_corpus.json";
const bytes = readFileSync("packages/data/worlds/fictional-eight-01.json");
const world = JSON.parse(bytes.toString("utf8"));
const manifest = JSON.parse(readFileSync("packages/data/worlds/fictional-eight-01.manifest.json", "utf8"));
const base = JSON.parse(readFileSync("tests/fixtures/world/t20-valid-setup.json", "utf8"));
const corpus = JSON.parse(readFileSync(corpusPath, "utf8")) as { recordCount: number; cases: unknown[] };
if (corpus.recordCount !== 100 || corpus.cases.length !== 100) throw new Error("BAD_INPUT_CORPUS_COUNT");

/** Wicket bands: 0-1, 2-3, 4-5, 6 or more down. */
const band = (wickets: number) => (wickets >= 6 ? 3 : Math.floor(wickets / 2));
const sums = Array.from({ length: 20 }, () => [0, 0, 0, 0]);
const counts = Array.from({ length: 20 }, () => [0, 0, 0, 0]);
let innings = 0;

type Delivery = { inningsIndex: number; legalBall: boolean; batRuns: number; dismissal: unknown; extras: Record<string, number> };
for (const raw of corpus.cases) {
  const setup = validateT20MatchSetup(createT20CorpusRequest(raw, base, world), bytes, manifest);
  const game = runFixtureT20(setup);
  let runs = 0, wickets = 0, legal = 0;
  const starts: { over: number; wickets: number; runs: number }[] = [{ over: 0, wickets: 0, runs: 0 }];
  for (const record of game.events as { payload?: { event?: { type: string } } }[]) {
    const event = record.payload?.event as unknown as (Delivery & { type: string }) | undefined;
    if (!event) continue;
    if (event.type !== "DELIVERY_RECORDED" || event.inningsIndex !== 0) continue;
    const extras = Object.values(event.extras).reduce((a, b) => a + b, 0);
    runs += event.batRuns + extras;
    if (event.dismissal) wickets += 1;
    if (event.legalBall) {
      legal += 1;
      if (legal % 6 === 0 && legal < 120 && wickets < 10) starts.push({ over: legal / 6, wickets, runs });
    }
  }
  const card = projectT20Scorecard(game);
  const total = card.innings[0]!.runs;
  if (total !== runs) throw new Error(`RUN_RECONCILIATION_${JSON.stringify(raw).slice(0, 40)}: ${runs} != ${total}`);
  for (const s of starts) {
    sums[s.over]![band(s.wickets)]! += total - s.runs;
    counts[s.over]![band(s.wickets)]! += 1;
  }
  innings += 1;
}

const rows = sums.map((row, over) => row.map((sum, b) => ({ n: counts[over]![b]!, meanX10: counts[over]![b]! ? Math.round((sum * 10) / counts[over]![b]!) : null })));
const corpusSha256 = createHash("sha256").update(readFileSync(corpusPath)).digest("hex");
const body = `/**
 * GENERATED by scripts/pavilion-t20-expectation.ts. Do not edit by hand.
 *
 * T20 first innings in the game's own model (synthetic-alpha-01, fixture autopilot, the frozen 100-match corpus):
 * for each over about to start (0 to 19) and each wicket band (0-1, 2-3, 4-5, 6 or more down), how many innings
 * passed through that point (n) and the mean runs they went on to add, times 10 (null where none did).
 * It describes this synthetic model, not real cricket.
 */
export const T20_EXPECTATION_TABLE = {
  version: "LC_T20_EXPECTATION_TABLE_V1",
  inputCorpusSha256: "${corpusSha256}",
  innings: ${innings},
  /** rows[over][band] */
  rows: ${JSON.stringify(rows)},
} as const;
`;
if (process.argv.includes("--check")) {
  const committed = readFileSync(OUT, "utf8");
  if (committed !== body) { console.error(`${OUT} differs from a fresh run`); process.exit(1); }
  console.log(JSON.stringify({ status: "PASS", innings, corpusSha256 }));
} else {
  writeFileSync(OUT, body);
  console.log(JSON.stringify({ status: "WRITTEN", out: OUT, innings, corpusSha256, overZero: rows[0], overTen: rows[10] }));
}
